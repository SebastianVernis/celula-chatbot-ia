#!/bin/bash

################################################################################
# Script de Optimización de Imágenes Responsivas
# Convierte JPG/PNG a WebP y AVIF en múltiples tamaños
# Genera template HTML con srcset y sizes
################################################################################

set -e  # Salir si hay error

# ============================================================================
# CONFIGURACIÓN - MODIFICAR SEGÚN NECESIDADES
# ============================================================================

INPUT_DIR="${1:-./assets/images}"
OUTPUT_DIR="${2:-./assets/images/optim}"
SIZES="${3:-480,800,1280}"
QUALITY_WEBP=85
QUALITY_AVIF=80

# ============================================================================
# COLORES PARA OUTPUT
# ============================================================================

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# ============================================================================
# FUNCIONES
# ============================================================================

print_header() {
    echo -e "\n${BLUE}════════════════════════════════════════════════════════${NC}"
    echo -e "${BLUE}  $1${NC}"
    echo -e "${BLUE}════════════════════════════════════════════════════════${NC}\n"
}

print_success() {
    echo -e "${GREEN}✓${NC} $1"
}

print_error() {
    echo -e "${RED}✗${NC} $1"
}

